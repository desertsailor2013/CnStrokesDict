#!/usr/bin/env node
/**
 * 构建完整的单字JSON文件
 * 合并笔画数据和释义数据，生成最终的 characters.json
 */

const fs = require('fs');
const path = require('path');

// 路径配置
const SCRIPTS_DIR = __dirname;
const RAW_DIR = path.join(SCRIPTS_DIR, "hanzi_raw");
const DATA_DIR = path.join(SCRIPTS_DIR, "dict_data");
const OUTPUT_DIR = path.join(SCRIPTS_DIR, "..", "app", "src", "main", "assets", "dictionary");

// 确保目录存在
[DATA_DIR, OUTPUT_DIR].forEach(dir => {
    if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
    }
});

/**
 * 加载JSON文件
 */
function loadJson(filePath) {
    if (!fs.existsSync(filePath)) {
        return null;
    }
    try {
        const data = fs.readFileSync(filePath, 'utf-8');
        return JSON.parse(data);
    } catch (e) {
        console.log(`加载失败: ${filePath} - ${e.message}`);
        return null;
    }
}

/**
 * 保存JSON文件
 */
function saveJson(data, filePath) {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf-8');
    console.log(`已保存: ${filePath}`);
}

/**
 * 加载笔画数据
 */
function loadStrokeData() {
    const strokeData = {};
    
    // 从合并文件加载
    const mergedFile = path.join(RAW_DIR, "all_chars_raw.json");
    const data = loadJson(mergedFile);
    if (data) {
        Object.assign(strokeData, data);
    }
    
    // 从单个文件加载
    if (fs.existsSync(RAW_DIR)) {
        const files = fs.readdirSync(RAW_DIR).filter(f => f.endsWith('.raw.json'));
        for (const file of files) {
            const char = file.replace('.raw.json', '');
            if (!strokeData[char]) {
                const data = loadJson(path.join(RAW_DIR, file));
                if (data) {
                    strokeData[char] = data;
                }
            }
        }
    }
    
    return strokeData;
}

/**
 * 加载生字清单
 */
function loadPrimaryChars() {
    const { getAllChars } = require('./primary_school_chars');
    return getAllChars();
}

