/**
 * 构建单字条目数据
 */
function buildCharEntry(char, strokeData) {
    const entry = {
        char: char,
        pinyin: PINYIN_DB[char] || "",
        radical: RADICAL_DB[char] || "",
        radicalStrokes: 0,
        totalStrokes: 0,
        shuowen: "",
        definitions: DEFINITIONS_DB[char] || [],
        words: [],
        idioms: [],
        strokes: [],
        evolution: [],
        strokeHints: [],
        pinyinWordExamples: [],
        source: "primary_school",
    };
    
    // 合并笔画数据
    if (strokeData && strokeData[char]) {
        const strokes = strokeData[char].strokes || [];
        entry.strokes = strokes;
        entry.totalStrokes = strokes.length;
        
        // 获取部首笔画数
        const radStrokes = strokeData[char].radStrokes || [];
        entry.radicalStrokeCount = radStrokes.length;
    }
    
    // 添加拼音组词示例
    if (entry.pinyin && entry.definitions.length > 0) {
        entry.pinyinWordExamples.push({
            pinyin: entry.pinyin,
            word: char,
        });
    }
    
    return entry;
}

/**
 * 构建完整的characters.json
 */
function buildCharactersJson() {
    console.log("加载生字清单...");
    const chars = loadPrimaryChars();
    console.log(`  生字数量: ${chars.length}`);
    
    console.log("加载笔画数据...");
    const strokeData = loadStrokeData();
    console.log(`  笔画数据: ${Object.keys(strokeData).length} 个`);
    
    console.log("构建条目...");
    const entries = chars.map(char => buildCharEntry(char, strokeData));
    
    return { characters: entries };
}

