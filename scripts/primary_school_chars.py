def get_all_chars() -> list[str]:
    """获取所有年级的生字列表（去重）"""
    all_chars = set()
    for grade_data in PRIMARY_SCHOOL_CHARS.values():
        for semester_chars in grade_data.values():
            all_chars.update(semester_chars)
    return sorted(list(all_chars))


def get_chars_by_grade(grade: str) -> list[str]:
    """获取指定年级的生字列表（去重）"""
    if grade not in PRIMARY_SCHOOL_CHARS:
        return []
    chars = set()
    for semester_chars in PRIMARY_SCHOOL_CHARS[grade].values():
        chars.update(semester_chars)
    return sorted(list(chars))


def get_grade_stats() -> dict:
    """获取各年级生字统计"""
    stats = {}
    for grade, data in PRIMARY_SCHOOL_CHARS.items():
        chars = set()
        for semester_chars in data.values():
            chars.update(semester_chars)
        stats[grade] = len(chars)
    stats["total"] = len(get_all_chars())
    return stats


if __name__ == "__main__":
    stats = get_grade_stats()
    print("小学1-6年级生字统计：")
    for grade, count in stats.items():
        print(f"  {grade}: {count}字")
    print(f"\n总计：{stats['total']}字")
